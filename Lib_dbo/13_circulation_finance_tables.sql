BEGIN
    FOR book_record IN (
        SELECT b.book_id, GREATEST(NVL(b.total_copies, 0) - COUNT(bc.copy_id), 0) AS missing_copies
        FROM books b
        LEFT JOIN book_copies bc ON bc.book_id = b.book_id
        GROUP BY b.book_id, b.total_copies
    ) LOOP
        FOR copy_index IN 1 .. book_record.missing_copies LOOP
            INSERT INTO book_copies (copy_id, book_id, branch_id, status)
            VALUES (seq_book_copies.NEXTVAL, book_record.book_id, NULL, 'AVAILABLE');
        END LOOP;
    END LOOP;
END;
/

MERGE INTO library_bnk_account bank
USING (SELECT 1 AS account_id FROM dual) seed
ON (bank.account_id = seed.account_id)
WHEN NOT MATCHED THEN
    INSERT (account_id, account_name, current_balance)
    VALUES (1, 'Library Fine Collection Account', 0);

COMMIT;
