BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE loan_charges (
            charge_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            loan_id NUMBER NOT NULL,
            member_id NUMBER NOT NULL REFERENCES members(member_id),
            charge_type VARCHAR2(20) NOT NULL,
            amount NUMBER(12, 2) NOT NULL,
            created_at DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT uq_loan_charge_type UNIQUE (loan_id, charge_type),
            CONSTRAINT ck_loan_charge_type CHECK (charge_type IN (''LATE_FEE'', ''LOST_BOOK'')),
            CONSTRAINT ck_loan_charge_amount CHECK (amount > 0)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE loan_charge_payments (
            payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            charge_id NUMBER NOT NULL REFERENCES loan_charges(charge_id),
            amount NUMBER(12, 2) NOT NULL,
