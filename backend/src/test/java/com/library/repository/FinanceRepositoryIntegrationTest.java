package com.library.repository;

import com.library.dto.BankAccountResponse;
import com.library.dto.FineDepositResponse;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.web.server.ResponseStatusException;

import java.math.BigDecimal;
import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

class FinanceRepositoryIntegrationTest {

    private JdbcTemplate jdbcTemplate;
    private FinanceRepository financeRepository;

    @BeforeEach
    void setUp() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:finance;MODE=Oracle;DB_CLOSE_DELAY=-1");
        jdbcTemplate = new JdbcTemplate(dataSource);
        jdbcTemplate.execute("DROP ALL OBJECTS");
        jdbcTemplate.execute("CREATE TABLE library_bnk_account (account_id BIGINT PRIMARY KEY, account_name VARCHAR(200), " +
                "account_reference VARCHAR(100), current_balance DECIMAL(14, 2), updated_at TIMESTAMP)");
        jdbcTemplate.execute("CREATE TABLE loan_charge_payments (payment_id BIGINT PRIMARY KEY, amount DECIMAL(14, 2))");
        jdbcTemplate.execute("CREATE TABLE app_users (user_id BIGINT PRIMARY KEY, username VARCHAR(200))");
        jdbcTemplate.execute("CREATE TABLE fine_deposits (deposit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                "account_id BIGINT, amount DECIMAL(14, 2), deposited_by BIGINT, deposited_at TIMESTAMP)");
        jdbcTemplate.update("INSERT INTO library_bnk_account VALUES (1, 'Library Fines', NULL, 0, SYSDATE)");
        jdbcTemplate.update("INSERT INTO loan_charge_payments VALUES (1, 25.50)");
        jdbcTemplate.update("INSERT INTO app_users VALUES (900, 'Library Admin')");
        financeRepository = new FinanceRepository(jdbcTemplate);
    }

    @Test
    void depositsAllCollectedFinesOnceAndUpdatesAccountBalance() {
        BankAccountResponse deposited = financeRepository.depositCollectedFines(900L);

        assertEquals(new BigDecimal("25.50"), deposited.getCurrentBalance());
        assertEquals(0, deposited.getAvailableToDeposit().compareTo(BigDecimal.ZERO));
        List<FineDepositResponse> deposits = financeRepository.findDeposits();
        assertEquals(1, deposits.size());
        assertEquals(new BigDecimal("25.50"), deposits.get(0).getAmount());
        assertThrows(ResponseStatusException.class, () -> financeRepository.depositCollectedFines(900L));
    }
}
