--------------------------------------------------------------------------------
-- Loan charges, fine payments, deposit ledger, and successful login activity
--------------------------------------------------------------------------------

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE loan_charges (
            charge_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            loan_id NUMBER NOT NULL,
            member_id NUMBER NOT NULL REFERENCES members(member_id),
            charge_type VARCHAR2(20) NOT NULL,
            amount NUMBER(12, 2) NOT NULL,
            created_at DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT uq_loan_charge_type UNIQUE (loan_id, charge_type),
            CONSTRAINT ck_loan_charge_type CHECK (charge_type IN (''LATE_FEE'', ''LOST_BOOK'')),
            CONSTRAINT ck_loan_charge_amount CHECK (amount > 0)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE loan_charge_payments (
            payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            charge_id NUMBER NOT NULL REFERENCES loan_charges(charge_id),
            amount NUMBER(12, 2) NOT NULL,
            received_by NUMBER NOT NULL REFERENCES app_users(user_id),
            received_at DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT ck_charge_payment_amount CHECK (amount > 0)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE library_bnk_account (
            account_id NUMBER PRIMARY KEY,
            account_name VARCHAR2(200) NOT NULL,
            account_reference VARCHAR2(100),
            current_balance NUMBER(14, 2) DEFAULT 0 NOT NULL,
            updated_at DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT ck_library_bank_balance CHECK (current_balance >= 0)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE fine_deposits (
            deposit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            account_id NUMBER NOT NULL REFERENCES library_bnk_account(account_id),
            amount NUMBER(14, 2) NOT NULL,
            deposited_by NUMBER NOT NULL REFERENCES app_users(user_id),
            deposited_at DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT ck_fine_deposit_amount CHECK (amount > 0)
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE login_activity (
            login_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id NUMBER NOT NULL REFERENCES app_users(user_id),
            logged_in_at DATE DEFAULT SYSDATE NOT NULL
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX idx_login_activity_time ON login_activity(logged_in_at)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

MERGE INTO library_bnk_account account
USING (SELECT 1 AS account_id FROM dual) seed
ON (account.account_id = seed.account_id)
WHEN NOT MATCHED THEN
    INSERT (account_id, account_name, current_balance)
    VALUES (1, 'Library Fine Collection Account', 0);

COMMIT;
