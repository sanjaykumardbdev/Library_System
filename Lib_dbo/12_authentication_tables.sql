--------------------------------------------------------------------------------
-- Authentication accounts linked to library members or operator-managed admins
--------------------------------------------------------------------------------

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE app_users (
            user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username VARCHAR2(200) NOT NULL,
            email VARCHAR2(200) NOT NULL,
            password_hash VARCHAR2(100) NOT NULL,
            member_id NUMBER UNIQUE,
            account_status VARCHAR2(20) DEFAULT ''ACTIVE'' NOT NULL,
            password_version NUMBER DEFAULT 0 NOT NULL,
            CONSTRAINT uq_app_users_email UNIQUE (email),
            CONSTRAINT fk_app_users_member FOREIGN KEY (member_id)
                REFERENCES members(member_id),
            CONSTRAINT ck_app_users_status CHECK (account_status IN (''ACTIVE'', ''DISABLED''))
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE app_users ADD (password_version NUMBER DEFAULT 0 NOT NULL)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE app_users ADD (must_change_password NUMBER(1) DEFAULT 0 NOT NULL)';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -1430 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE app_user_roles (
            user_id NUMBER NOT NULL,
            role VARCHAR2(30) NOT NULL,
            CONSTRAINT pk_app_user_roles PRIMARY KEY (user_id, role),
            CONSTRAINT fk_app_user_roles_user FOREIGN KEY (user_id)
                REFERENCES app_users(user_id) ON DELETE CASCADE,
            CONSTRAINT ck_app_user_roles_role CHECK (role IN (''MEMBER'', ''ADMIN''))
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
